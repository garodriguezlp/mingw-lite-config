####################################################################################################
# FUNCTIONS
####################################################################################################
# Go up one directory
__cd_up__() {
    cd ..
}

####################################################################################################
# KEY BINDINGS
####################################################################################################
# Bind Shift+Up Arrow to execute the "cd_up" command (interactive sessions only)
if [[ $- =~ i ]]; then
    bind '"\e[1;2A": "__cd_up__\n"'
fi